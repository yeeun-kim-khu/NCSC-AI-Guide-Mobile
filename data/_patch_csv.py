# Read
with open(CSV_PATH, encoding="utf-8-sig", newline="") as f:
    rows = list(csv.DictReader(f))
    f.seek(0)
    reader = csv.reader(f)
    header = next(reader)
    raw_rows = list(reader)

# Ensure 학습목표·차시별내용 in header
if "학습목표" not in header:
    header.append("학습목표")
if "차시별내용" not in header:
    header.append("차시별내용")

prog_idx = header.index("프로그램명")
sub_idx = header.index("세부프로그램명")
month_idx = header.index("월")
notice_idx = header.index("유의사항")
goal_idx = header.index("학습목표")
detail_idx = header.index("차시별내용")

for row in raw_rows:
    # pad missing columns
    while len(row) < len(header):
        row.append("")

    prog = row[prog_idx]
    sub = row[sub_idx]
    month = row[month_idx]

    # build lookup key (use _5월 suffix to distinguish 5월/6월 어린이맞춤)
    key = (prog, sub)
    key_m = (prog + "_" + month, sub)

    patch = PATCHES.get(key_m) or PATCHES.get(key)
    if patch is None:
        continue

    if patch.get("학습목표") and not row[goal_idx]:
        row[goal_idx] = patch["학습목표"]
    if patch.get("차시별내용") and not row[detail_idx]:
        row[detail_idx] = patch["차시별내용"]
    if "유의사항_append" in patch:
        row[notice_idx] += patch["유의사항_append"]
    if "유의사항_replace" in patch:
        row[notice_idx] = patch["유의사항_replace"]

# Write back
with open(CSV_PATH, "w", encoding="utf-8-sig", newline="") as f:
    writer = csv.writer(f)
    writer.writerow(header)
    writer.writerows(raw_rows)

print("패치 완료!")
for row in raw_rows:
    if len(row) > goal_idx and row[goal_idx]:
        print(f"  ✓ {row[month_idx]}월 {row[prog_idx]} - {row[sub_idx][:20]}")
